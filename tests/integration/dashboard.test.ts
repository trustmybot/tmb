// The dashboard, run as `tmb dashboard` over a prepared record: the page and its bundled
// script and styles, every API read, the Human's changes through the engine's operations and
// the refusals that guard them, and every page rendered against the running server.
import { GlobalRegistrator } from "@happy-dom/global-registrator";
import { afterAll, beforeAll, describe, expect, setDefaultTimeout, test } from "bun:test";
import { type ChildProcess, spawn, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { createInterface } from "node:readline";
import { SEED, type SeededIds, seedRecord } from "./dashboard-record.ts";

// Every test file sets this: bun's 5s fails slow tests on a busy machine (tests/README.md).
setDefaultTimeout(30_000);

const ROOT = path.resolve(import.meta.dir, "../..");
const CLI = path.join(ROOT, "src", "cli", "index.ts");
const WEB = path.join(ROOT, "src", "dashboard", "web");

let scratch: string;
let ids: SeededIds;
let child: ChildProcess;
let base: string;
let realFetch: typeof fetch;

const GRAPH_SOURCE = `export function toggleTheme(dark: boolean): string {
  return pick(dark);
}

function pick(dark: boolean): string {
  return [dark].map((d) => (d ? "dark" : "light"))[0]!;
}
`;

/** Starts `tmb dashboard` from outside the repository, so the page's build settings must come from --config. */
function startDashboard(projectDir: string): Promise<string> {
  child = spawn(process.execPath, [`--config=${path.join(ROOT, "bunfig.toml")}`, CLI, "dashboard", "--port", "0", "--project", projectDir], {
    cwd: scratch,
    stdio: ["ignore", "pipe", "pipe"],
  });
  let stderr = "";
  child.stderr!.on("data", (chunk) => (stderr += String(chunk)));
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`tmb dashboard did not start: ${stderr}`)), 30_000);
    child.once("exit", (code) => reject(new Error(`tmb dashboard exited ${code}: ${stderr}`)));
    createInterface({ input: child.stdout! }).on("line", (line) => {
      const match = /: (http:\/\/127\.0\.0\.1:\d+\/)$/.exec(line);
      if (match) {
        clearTimeout(timer);
        resolve(match[1]!);
      }
    });
  });
}

beforeAll(async () => {
  realFetch = globalThis.fetch;
  scratch = realpathSync(mkdtempSync(path.join(tmpdir(), "tmb-dashboard-")));
  ids = seedRecord(scratch);
  // A git repository, so the code graph page has a base branch to read.
  mkdirSync(path.join(scratch, "src"), { recursive: true });
  writeFileSync(path.join(scratch, "src", "theme.ts"), GRAPH_SOURCE);
  for (const args of [["init", "-q", "-b", "main"], ["add", "src"], ["-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-q", "-m", "first"]]) {
    const result = spawnSync("git", args, { cwd: scratch, encoding: "utf8" });
    if (result.status !== 0) throw new Error(`git ${args.join(" ")}: ${result.stderr}`);
  }
  base = await startDashboard(scratch);
}, 60_000);

afterAll(async () => {
  if (GlobalRegistrator.isRegistered) await GlobalRegistrator.unregister();
  globalThis.fetch = realFetch;
  child?.kill("SIGTERM");
  rmSync(scratch, { recursive: true, force: true });
});

const api = async (route: string) => {
  const res = await realFetch(new URL(`api/${route}`, base));
  expect(res.status).toBe(200);
  return (await res.json()) as any;
};

async function token(): Promise<string> {
  return (await api("token")).token as string;
}

function post(route: string, body: unknown, headers: Record<string, string> = {}) {
  return realFetch(new URL(`api/${route}`, base), {
    method: "POST",
    headers: { "content-type": "application/json", ...headers },
    body: JSON.stringify(body),
  });
}

describe("the page", () => {
  test("serves the HTML with its bundled script and Tailwind styles", async () => {
    const html = await (await realFetch(base)).text();
    expect(html).toContain('<div id="root"></div>');
    const script = /<script type="module"[^>]*src="([^"]+)"/.exec(html)?.[1];
    const style = /<link rel="stylesheet"[^>]*href="([^"]+)"/.exec(html)?.[1];
    expect(script).toBeDefined();
    expect(style).toBeDefined();
    const js = await (await realFetch(new URL(script!, base))).text();
    // The app itself, not just a shell: the tab names are in the bundle.
    expect(js.includes("Runs & Gates")).toBe(true);
    const css = await (await realFetch(new URL(style!, base))).text();
    // A class the pages use, generated by Tailwind from the Primer tokens.
    expect(css).toMatch(/\.bg-canvas\s*\{[^}]*var\(--bgColor-default\)/);
  });

  test("answers 404 to an unknown path and an unknown API", async () => {
    expect((await realFetch(new URL("nope", base))).status).toBe(404);
    const res = await realFetch(new URL("api/nope", base));
    expect(res.status).toBe(404);
    expect(((await res.json()) as any).error).toBe("not_found");
  });
});

describe("the API reads the record", () => {
  test("summary", async () => {
    const s = await api("summary");
    expect(s.issues).toEqual({ open: 1, closed: 1 });
    expect(s.tasks_by_state).toEqual([{ state: "open", count: 1 }]);
    expect(s.open_features).toBe(1);
    expect(s.open_runs).toBe(1);
    expect(s.recent_runs).toHaveLength(2);
  });

  test("issues and one issue in full", async () => {
    const list = await api("issues");
    const issue = list.find((i: any) => i.id === ids.issueId);
    expect(issue).toMatchObject({ title: SEED.issueTitle, state: "open", milestone: SEED.milestone, task_count: 1, tasks_done: 0, discussion_count: 3, author: "planner" });
    expect(list.find((i: any) => i.id === ids.closedIssueId)).toMatchObject({ state: "closed", author: "human" });
    const detail = await api(`issues/${ids.issueId}`);
    expect(detail.issue.body).toBe(SEED.issueBody);
    expect(detail.discussions.map((d: any) => d.body)).toEqual([SEED.note, SEED.oldDecision, SEED.decision]);
    expect(detail.decision_in_force).toBe(ids.decisionId);
    expect(detail.tasks.map((t: any) => t.title)).toEqual([SEED.taskTitle]);
    expect(detail.milestones).toEqual([SEED.milestone]);
    expect((await realFetch(new URL("api/issues/missing", base))).status).toBe(404);
  });

  test("tasks and one task in full", async () => {
    const [task] = await api("tasks");
    expect(task).toMatchObject({ id: ids.taskId, title: SEED.taskTitle, issue_title: SEED.issueTitle, feature_name: SEED.featureName, branch: SEED.branch, kind: "code", last_check: "failed" });
    const detail = await api(`tasks/${ids.taskId}`);
    expect(detail.task.spec).toBe(SEED.taskSpec);
    expect(detail.check_runs).toHaveLength(1);
    expect(detail.check_runs[0].commands.map((c: any) => [c.command, c.status, c.outputTail])).toEqual([
      [SEED.checkCommand, "passed", SEED.checkOutput],
      [SEED.failedCommand, "failed", SEED.failedOutput],
    ]);
    expect(detail.runs).toHaveLength(1);
    expect(detail.runs[0]).toMatchObject({ role: "worker", outcome: "stopped" });
    expect((await realFetch(new URL("api/tasks/missing", base))).status).toBe(404);
  });

  test("features, runs, checks, gate decisions and the audit log", async () => {
    expect((await api("features"))[0]).toMatchObject({ id: ids.featureId, name: SEED.featureName, task_count: 1, open_task_count: 1 });
    const runs = await api("runs");
    expect(runs.map((r: any) => r.role).sort()).toEqual(["planner", "worker"]);
    // A worker's run names its feature branch through its task (trustmybot/tmb#135).
    expect(runs.find((r: any) => r.role === "worker")).toMatchObject({ feature_id: ids.featureId, feature_name: SEED.featureName });
    expect(await api("runs?limit=1")).toHaveLength(1);
    expect((await api("checks"))[0]).toMatchObject({ task_id: ids.taskId, result: "failed" });
    expect((await api("guard-decisions"))[0]).toMatchObject({ decision: "deny", reason: SEED.guardReason, author: "worker" });
    expect((await api("audit"))[0]).toMatchObject({ what: SEED.auditWhat, detail: SEED.auditDetail, author: "human" });
    expect(typeof (await api("version")).data_version).toBe("number");
  });
});

describe("the API reads the code graph", () => {
  test("a folder, one level at a time, with function counts", async () => {
    const top = await api("graph/tree?path=.");
    expect(top.baseBranch).toBe("main");
    expect(top.functions).toBe(3);
    expect(top.children.find((c: any) => c.path === "src")).toMatchObject({ kind: "dir", functions: 3 });
    const src = await api("graph/tree?path=src");
    expect(src.children).toEqual([{ kind: "file", path: "src/theme.ts", name: "theme.ts", lang: "typescript", lane: "product", functions: 3, notParsed: null, area: null }]);
  });

  test("a file's functions, each inside its container, and one function with its callers and callees", async () => {
    const theme = await api("graph/file?path=src/theme.ts");
    const by = (name: string) => theme.symbols.find((s: any) => s.qualifiedName === name);
    expect(by("callback of `map`").parent).toBe(by("pick").id);
    expect(theme.links).toContainEqual({ from: by("toggleTheme").id, to: by("pick").id, count: 1 });
    const pick = await api(`graph/function/${by("pick").id}`);
    expect(pick.callers).toEqual([{ id: by("toggleTheme").id, qualifiedName: "toggleTheme", kind: "function", path: "src/theme.ts", lines: [2], moreLines: 0 }]);
    const found = await api("graph/search?q=toggle");
    expect(found.hits.map((h: any) => h.qualifiedName)).toEqual(["toggleTheme"]);
  });

  test("answers 404 to a path or function the graph does not hold", async () => {
    for (const route of ["graph/tree?path=nope", "graph/file?path=nope.ts", "graph/function/999999", "graph/function/abc"]) {
      const res = await realFetch(new URL(`api/${route}`, base));
      expect(res.status).toBe(404);
    }
  });
});

describe("the Human's changes", () => {
  test("refuses a request to another host name", async () => {
    const res = await realFetch(new URL("api/issues", base), { headers: { host: "evil.example:80" } });
    expect(res.status).toBe(403);
    expect(((await res.json()) as any).error).toBe("forbidden_host");
  });

  test("refuses a change without the token, or not sent as JSON", async () => {
    const before = await api(`issues/${ids.issueId}`);
    expect((await post(`issues/${ids.issueId}/comment`, { body: "no token" })).status).toBe(403);
    expect((await post(`issues/${ids.issueId}/comment`, { body: "bad token" }, { "x-tmb-token": "0".repeat(64) })).status).toBe(403);
    const plain = await realFetch(new URL(`api/issues/${ids.issueId}/comment`, base), {
      method: "POST",
      headers: { "content-type": "text/plain", "x-tmb-token": await token() },
      body: JSON.stringify({ body: "plain" }),
    });
    expect(plain.status).toBe(415);
    expect((await api(`issues/${ids.issueId}`)).discussions).toHaveLength(before.discussions.length);
  });

  test("records a note and a decision as the Human", async () => {
    const t = await token();
    expect((await post(`issues/${ids.issueId}/comment`, { body: "A note from the page." }, { "x-tmb-token": t })).status).toBe(200);
    expect((await post(`issues/${ids.issueId}/comment`, { body: "Ship it behind a flag.", kind: "decision" }, { "x-tmb-token": t })).status).toBe(200);
    const detail = await api(`issues/${ids.issueId}`);
    const [note, decision] = detail.discussions.slice(-2);
    expect(note).toMatchObject({ kind: "note", body: "A note from the page.", author: "human" });
    expect(decision).toMatchObject({ kind: "decision", author: "human" });
    expect(detail.decision_in_force).toBe(decision.id);
  });

  test("an invalid change is refused by the engine's own rule", async () => {
    const res = await post(`issues/${ids.issueId}/comment`, { body: "x", kind: "verdict" }, { "x-tmb-token": await token() });
    expect(res.status).toBe(400);
    expect(((await res.json()) as any).error).toBe("invalid_input");
  });

  test("edits an issue, and refuses an edit made from a stale page", async () => {
    const t = await token();
    const { issue } = await api(`issues/${ids.issueId}`);
    const edit = await post(`issues/${ids.issueId}/edit`, { title: "Add a dark mode switch", updated_at: issue.updated_at }, { "x-tmb-token": t });
    expect(edit.status).toBe(200);
    const stale = await post(`issues/${ids.issueId}/edit`, { title: "Stale title", updated_at: issue.updated_at }, { "x-tmb-token": t });
    expect(stale.status).toBe(409);
    expect(((await stale.json()) as any).error).toBe("stale");
    expect((await api(`issues/${ids.issueId}`)).issue.title).toBe("Add a dark mode switch");
  });

  test("closes and reopens an issue", async () => {
    const t = await token();
    const read = async () => (await api(`issues/${ids.closedIssueId}`)).issue;
    expect((await post(`issues/${ids.closedIssueId}/reopen`, { updated_at: (await read()).updated_at }, { "x-tmb-token": t })).status).toBe(200);
    expect((await read()).state).toBe("open");
    expect((await post(`issues/${ids.closedIssueId}/close`, { updated_at: (await read()).updated_at }, { "x-tmb-token": t })).status).toBe(200);
    expect((await read()).state).toBe("closed");
    expect((await post("issues/missing/close", { updated_at: "x" }, { "x-tmb-token": t })).status).toBe(404);
    // A change to the issue itself must say which version the page read.
    expect((await post(`issues/${ids.closedIssueId}/reopen`, {}, { "x-tmb-token": t })).status).toBe(400);
  });
});

describe("every page shows its data", () => {
  // The root tsconfig has no DOM types, so the few DOM pieces used here are typed by hand.
  type Node = { textContent: string | null; appendChild(child: Node): void };
  const dom = () => globalThis as unknown as { document: { body: Node; createElement(tag: string): Node }; window: { location: { hash: string } } };
  let root: Node;

  beforeAll(async () => {
    GlobalRegistrator.register({ url: base });
    // A non-literal path keeps the pages, which the dashboard's own tsconfig checks, out of the root typecheck.
    const app = path.join(WEB, "App.tsx");
    const [{ App }, { createRoot }, { QueryClient, QueryClientProvider }, { createElement }] = await Promise.all([
      import(app),
      import("react-dom/client"),
      import("@tanstack/react-query"),
      import("react"),
    ]);
    root = dom().document.createElement("div");
    dom().document.body.appendChild(root);
    const client = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity } } });
    createRoot(root).render(createElement(QueryClientProvider, { client }, createElement(App)));
  });

  async function show(hash: string, ...texts: string[]): Promise<void> {
    dom().window.location.hash = hash;
    const deadline = Date.now() + 10_000;
    while (Date.now() < deadline) {
      const text = root.textContent ?? "";
      if (texts.every((t) => text.includes(t))) return;
      await new Promise((resolve) => setTimeout(resolve, 50));
    }
    const missing = texts.filter((t) => !(root.textContent ?? "").includes(t));
    throw new Error(`${hash} never showed ${JSON.stringify(missing)}; it shows: ${(root.textContent ?? "").slice(0, 1500)}`);
  }

  test("overview", async () => {
    await show("#/overview", "Open Issues", "Open Feature Branches", "Add a dark mode switch", "Recent Agent Runs", SEED.taskTitle);
  });

  test("issues, open and closed", async () => {
    await show("#/issues", "Add a dark mode switch", SEED.milestone);
    await show("#/issues?state=closed", SEED.closedIssueTitle);
  });

  test("one issue: body, notes, the decision in force, tasks and feature branch", async () => {
    await show(`#/issues/${ids.issueId}`, "Add a dark mode switch", "dark mode", SEED.note, SEED.oldDecision, "Earlier decision", "Decision in force", SEED.taskTitle, SEED.featureName, "0 / 1");
  });

  test("tasks", async () => {
    await show("#/tasks", SEED.taskTitle, SEED.branch, SEED.featureName);
  });

  test("one task: spec, check commands with their output, and its agent runs", async () => {
    await show(`#/tasks/${ids.taskId}`, "ThemeToggle", SEED.checkCommand, SEED.checkOutput, SEED.failedCommand, SEED.failedOutput, "Agent Runs", "stopped", SEED.branch);
  });

  test("runs, checks and gate decisions", async () => {
    await show("#/runs", "Agent Runs", "Check Runs", "Gate Decisions", SEED.taskTitle, SEED.guardReason);
  });

  test("audit", async () => {
    await show("#/audit", SEED.auditWhat, SEED.auditDetail);
  });

  test("code: folders, then a file's functions, then one function", async () => {
    await show("#/code", "Code Graph", "src/", "3 functions", "From the graph of main");
    await show("#/code?file=src/theme.ts", "toggleTheme", "pick", "callback of `map`", "3 functions in this file");
    const theme = await api("graph/file?path=src/theme.ts");
    const pick = theme.symbols.find((s: any) => s.qualifiedName === "pick");
    await show(`#/code?fn=${pick.id}`, "Callers", "toggleTheme", "lines 5–7");
  });
});
