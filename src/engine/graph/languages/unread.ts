/**
 * The programming language tmb does not read that a file is in, by its last ending; null for a
 * language tmb reads, and for prose, data, config, markup, images and endings it does not know.
 * Code in an ending not in the map is not counted until trustmybot/tmb#154 brings Linguist's list.
 */
export function unreadLanguageOf(relPath: string): string | null {
  const name = relPath.slice(relPath.lastIndexOf("/") + 1);
  const dot = name.lastIndexOf(".");
  if (dot <= 0) return null;
  return UNREAD_LANGUAGES[name.slice(dot + 1).toLowerCase()] ?? null;
}
