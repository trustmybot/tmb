// Writes globals.ts (trustmybot/tmb#252): the global values the TypeScript compiler declares in
// its default library, and the callable members it declares on each. It asks the compiler at the
// version tmb pins for way B, a development dependency of tmb, and copies nothing by hand. Run it
// after the pin moves: `bun src/engine/graph/languages/typescript/globals.gen.ts`. A test fails when
// globals.ts is not what this writes.
import { writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript5";

/** The file this writes, beside it. */
export const GLOBALS_FILE = path.join(import.meta.dir, "globals.ts");

/** A file with no names of its own, so its scope holds only the library's globals. */
const PROBE = "/__tmb_globals_probe__.ts";

/**
 * Every global value of the compiler's default library for the newest target, the library a
 * program gets when it names none, with the members on its type that can be called.
 */
export function compilerGlobals(): Map<string, string[]> {
  const options: ts.CompilerOptions = { target: ts.ScriptTarget.ESNext, noEmit: true, types: [] };
  const host = ts.createCompilerHost(options, true);
  const { getSourceFile, fileExists } = host;
  host.getSourceFile = (file, version, onError) => (file === PROBE ? ts.createSourceFile(file, "export {};", version, true) : getSourceFile.call(host, file, version, onError));
  host.fileExists = (file) => file === PROBE || fileExists.call(host, file);
  const program = ts.createProgram([PROBE], options, host);
  const checker = program.getTypeChecker();
  // A member keyed by a symbol, `[Symbol.species]`, has no name a call can write; the compiler's
  // internal name for it carries an id that depends on what the process compiled before.
  const keyedBySymbol = (symbol: ts.Symbol): boolean =>
    (symbol.declarations ?? []).some((d) => {
      const name = ts.getNameOfDeclaration(d);
      return name !== undefined && ts.isComputedPropertyName(name);
    });
  const callable = (symbol: ts.Symbol): boolean => {
    if (keyedBySymbol(symbol)) return false;
    if ((symbol.flags & ts.SymbolFlags.Method) !== 0) return true;
    const type = checker.getTypeOfSymbol(symbol);
    return type.getCallSignatures().length > 0 || type.getConstructSignatures().length > 0;
  };
  const globals = new Map<string, string[]>();
  for (const symbol of checker.getSymbolsInScope(program.getSourceFile(PROBE)!, ts.SymbolFlags.Value)) {
    const decls = symbol.declarations ?? [];
    if (decls.length === 0 || !decls.every((d) => program.isSourceFileDefaultLibrary(d.getSourceFile()))) continue;
    const members = checker.getTypeOfSymbol(symbol).getProperties().filter(callable).map((p) => p.name);
    globals.set(symbol.name, [...new Set(members)].sort());
  }
  return new Map([...globals].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** The text of globals.ts. */
export function globalsText(): string {
  const lines = [...compilerGlobals()].map(([name, members]) => `  [${JSON.stringify(name)}, ${JSON.stringify(members.join(" "))}],`);
  return [
    `// Generated by globals.gen.ts from the TypeScript ${ts.version} compiler's default library. Do not edit.`,
    "// Each global value, and the members on its type that can be called, space-separated.",
    "const ENTRIES: readonly (readonly [string, string])[] = [",
    ...lines,
    "];",
    "",
    "/** The global values of the compiler's default library, each with the callable members it declares. */",
    "export const GLOBALS: ReadonlyMap<string, ReadonlySet<string>> = new Map(ENTRIES.map(([name, members]) => [name, new Set(members === \"\" ? [] : members.split(\" \"))]));",
    "",
  ].join("\n");
}

if (import.meta.main) writeFileSync(GLOBALS_FILE, globalsText());
