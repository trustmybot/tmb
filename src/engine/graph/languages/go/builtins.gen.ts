// Writes builtins.ts (trustmybot/tmb#352): the names Go's universe scope declares that a call can
// name, as the `go` found on PATH lists them through go/types: each predeclared function, such as
// `len`, and each predeclared type, such as `int`, whose call is a conversion (Go spec,
// "Predeclared identifiers", "Conversions"). Nothing is typed out by hand. Run it with the Go the
// list should follow: `bun src/engine/graph/languages/go/builtins.gen.ts`. A test fails when
// builtins.ts is not what this writes with the same Go release, and is skipped, saying why, without one.
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

/** The file this writes, beside it. */
export const BUILTINS_FILE = path.join(import.meta.dir, "builtins.ts");

/** Asks go/types for the release and each callable name of the universe scope. */
const PROGRAM = `package main

import (
	"encoding/json"
	"go/types"
	"os"
	"runtime"
	"strings"
)

func main() {
	names := []string{}
	for _, n := range types.Universe.Names() {
		switch types.Universe.Lookup(n).(type) {
		case *types.Builtin, *types.TypeName:
			names = append(names, n)
		}
	}
	v := runtime.Version()
	if i := strings.Index(v[len("go1."):], "."); i >= 0 {
		v = v[:len("go1.")+i]
	}
	json.NewEncoder(os.Stdout).Encode(map[string]any{"version": v, "names": names})
}
`;

export type GoBuiltins = { version: string; names: string[] };

/** The callable universe names of the Go on PATH, by its release (`go1.27`), or null when there is none. */
export function goBuiltins(go = "go"): GoBuiltins | null {
  const dir = mkdtempSync(path.join(tmpdir(), "tmb-go-builtins-"));
  try {
    const file = path.join(dir, "main.go");
    writeFileSync(file, PROGRAM);
    const run = spawnSync(go, ["run", file], { encoding: "utf8", cwd: dir });
    if (run.status !== 0 || run.error) return null;
    const parsed = JSON.parse(run.stdout) as GoBuiltins;
    return { version: parsed.version, names: [...parsed.names].sort() };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** The text of builtins.ts for these built-ins. */
export function builtinsText(builtins: GoBuiltins): string {
  return [
    `// Generated by builtins.gen.ts from ${builtins.version}'s universe scope (go/types). Do not edit.`,
    "// Each predeclared function and type: a call can name them.",
    `export const BUILTINS_GO_VERSION = ${JSON.stringify(builtins.version)};`,
    "",
    "/** The names Go predeclares that a call can name: a built-in function, or a type the call converts to. */",
    `export const BUILTINS: ReadonlySet<string> = new Set(${JSON.stringify(builtins.names.join(" "))}.split(" "));`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const builtins = goBuiltins();
  if (builtins === null) throw new Error("no go on PATH");
  writeFileSync(BUILTINS_FILE, builtinsText(builtins));
}
