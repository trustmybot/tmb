// Writes builtins.ts (trustmybot/tmb#252): the names of Python's `builtins` module, the last
// place Python's lookup looks, and the callable attributes of each, as the Python found on PATH
// lists them. Nothing is typed out by hand. Run it with the Python the list should follow:
// `bun src/engine/graph/languages/python/builtins.gen.ts`. A test fails when builtins.ts is not
// what this writes with the same Python version, and is skipped, saying why, without one.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

/** The file this writes, beside it. */
export const BUILTINS_FILE = path.join(import.meta.dir, "builtins.ts");

/** Asks Python for its version and each name of `builtins` with its callable attributes. */
const PROGRAM = [
  "import builtins, json, sys",
  "names = {n: sorted(a for a in dir(getattr(builtins, n)) if callable(getattr(getattr(builtins, n), a, None))) for n in dir(builtins)}",
  "print(json.dumps({'version': '%d.%d' % sys.version_info[:2], 'names': names}))",
].join("\n");

export type PythonBuiltins = { version: string; names: Map<string, string[]> };

/** The builtins of the Python on PATH, or null when there is none. */
export function pythonBuiltins(python = "python3"): PythonBuiltins | null {
  const run = spawnSync(python, ["-I", "-c", PROGRAM], { encoding: "utf8" });
  if (run.status !== 0 || run.error) return null;
  const parsed = JSON.parse(run.stdout) as { version: string; names: Record<string, string[]> };
  return { version: parsed.version, names: new Map(Object.entries(parsed.names).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) };
}

/** The text of builtins.ts for these builtins. */
export function builtinsText(builtins: PythonBuiltins): string {
  const lines = [...builtins.names].map(([name, members]) => `  [${JSON.stringify(name)}, ${JSON.stringify(members.join(" "))}],`);
  return [
    `// Generated by builtins.gen.ts from Python ${builtins.version}'s \`builtins\` module. Do not edit.`,
    "// Each name, and its attributes that can be called, space-separated.",
    `export const BUILTINS_PYTHON_VERSION = ${JSON.stringify(builtins.version)};`,
    "const ENTRIES: readonly (readonly [string, string])[] = [",
    ...lines,
    "];",
    "",
    "/** The names of Python's `builtins` module, each with its callable attributes. */",
    "export const BUILTINS: ReadonlyMap<string, ReadonlySet<string>> = new Map(ENTRIES.map(([name, members]) => [name, new Set(members === \"\" ? [] : members.split(\" \"))]));",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const builtins = pythonBuiltins();
  if (builtins === null) throw new Error("no python3 on PATH");
  writeFileSync(BUILTINS_FILE, builtinsText(builtins));
}
